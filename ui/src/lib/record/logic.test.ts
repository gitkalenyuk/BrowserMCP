import { describe, expect, it } from 'vitest';
import type { RecordStep } from '../api/types-record-runs';
import { buildInputs, describeStep, fileUrl, inferInputs, parseStepsJsonl, scriptName, upsertStep, visibleSteps } from './logic';

const step = (seq: number, over: Partial<RecordStep> = {}): RecordStep => ({ seq, ts_ms: 1000 + seq, source: 'human', action: 'click', ...over });

describe('steps', () => {
  it('upserts by seq and keeps order', () => {
    let s = upsertStep([], step(1));
    s = upsertStep(s, step(3));
    s = upsertStep(s, step(2));
    expect(s.map((x) => x.seq)).toEqual([1, 2, 3]);
    s = upsertStep(s, step(2, { action: 'fill', value: 'x' }));
    expect(s).toHaveLength(3);
    expect(s[1].action).toBe('fill');
  });

  it('parses jsonl and hides human copies of API steps', () => {
    const text = `${JSON.stringify(step(1, { action: 'start', source: 'system', url: 'https://a.test/' }))}\n${JSON.stringify(step(2, { dup_of: 1 }))}\n{"seq":`;
    const steps = parseStepsJsonl(text);
    expect(steps).toHaveLength(2);
    expect(visibleSteps(steps).map((x) => x.seq)).toEqual([1]);
  });

  it('describes steps', () => {
    expect(describeStep(step(1, { target: { role: 'button', name: 'Sign in' } }))).toMatchObject({ kind: 'action', verb: 'Click', target: 'button "Sign in"' });
    expect(describeStep(step(1, { action: 'fill', secret: true, value: '***', target: { role: 'textbox', name: 'Password' } }))).toMatchObject({ verb: 'Fill', value: '***' });
    expect(describeStep(step(1, { action: 'goto', url: 'https://x.test/' }))).toMatchObject({ kind: 'nav', target: 'https://x.test/' });
    expect(
      describeStep(step(1, { source: 'api', action: 'command', command: { name: 'page.read', call_id: 1, caller: {}, args: {}, ok: false, error: 'TIMEOUT' } })),
    ).toMatchObject({ kind: 'command', verb: 'page.read', failed: true, value: 'TIMEOUT' });
    expect(describeStep(step(1, { target: { css: '#a > b' } })).target).toBe('#a > b');
  });
});

const CODE = `// Generated by BrowserMCP
// Inputs (--input key=value):
//   email  Email
function need(key: string): string {
  const value = inputs[key];
  return value;
}
await browser.nav.goto({ url: inputs.start_url ?? "https://shop.test/" });
await act("textbox", "Email", "fill", inputs.email ?? "ann@example.test");
await act("textbox", "Password", "fill", need("password"));
await act("combobox", "Country", "select", inputs['country'] ?? 'Norway');
await act("textbox", "Coupon", "fill", inputs.coupon);
/* await act("textbox", "Old", "fill", inputs.old ?? "x"); */
await act("textbox", "Email again", "fill", inputs.email ?? "other@example.test");
`;

describe('inferInputs', () => {
  it('finds inputs.<name>, inputs["name"] and need("name") with defaults', () => {
    const got = inferInputs(CODE, [
      { name: 'email', label: 'Email', default: 'ann@example.test', secret: false },
      { name: 'password', label: 'Password', default: null, secret: true },
    ]);
    expect(got).toEqual([
      { name: 'start_url', default: 'https://shop.test/', required: false, secret: false, label: 'start_url' },
      { name: 'email', default: 'ann@example.test', required: false, secret: false, label: 'Email' },
      { name: 'password', default: null, required: true, secret: true, label: 'Password' },
      { name: 'country', default: 'Norway', required: false, secret: false, label: 'country' },
      { name: 'coupon', default: null, required: true, secret: false, label: 'coupon' },
    ]);
  });

  it('decodes escaped defaults and ignores dynamic keys', () => {
    expect(inferInputs('x = inputs.q ?? "a \\"b\\" \\u00e9"; y = inputs[k];')).toEqual([
      { name: 'q', default: 'a "b" é', required: false, secret: false, label: 'q' },
    ]);
  });

  it('builds the run inputs and reports missing required ones', () => {
    const defs = inferInputs(CODE);
    expect(buildInputs(defs, { email: 'z@z.test', coupon: '' })).toEqual({
      inputs: { email: 'z@z.test' },
      missing: ['password', 'coupon'],
    });
  });
});

describe('names and paths', () => {
  it('makes a valid script name', () => {
    expect(scriptName(' Log in to shop.ts ')).toBe('Log-in-to-shop');
    expect(scriptName('a'.repeat(80))).toHaveLength(64);
  });

  it('turns a Windows path into a file URL', () => {
    expect(fileUrl('C:\\Users\\me\\data\\recordings\\r 1\\video.webm')).toBe('file:///C:/Users/me/data/recordings/r%201/video.webm');
    expect(fileUrl('C:\\data\\r1\\video.webm', true)).toBe('file:///C:/data/r1/');
    expect(fileUrl('/home/me/v.webm')).toBe('file:///home/me/v.webm');
  });
});
